// Keeps public/images/ and the blur placeholders in step with data/image-slots.ts.
//   npm run images:sync      (also runs automatically before `npm run build`)
//
// 1. Drop-in replacement: any file in public/images/new/ whose name matches a slot (service-seo.png,
//    service-seo.jpg, service-seo.webp ...) is converted to that slot's size as WebP (quality 80),
//    written over public/images/<slot file>, and removed from new/. So replacing an image only needs
//    the same slot name (extension does not matter).
// 2. Regenerates data/image-blurs.ts: a tiny blur placeholder for every slot image.
// Slots whose file is missing are listed (the site shows the branded illustration for them).
import { existsSync } from "node:fs";
import { mkdir, readdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";
import { slotList } from "../data/image-slots.ts";

const DIR = path.join("public", "images");
const NEW_DIR = path.join(DIR, "new");
const SIZE_PX = { card: [1536, 1024], wide: [2400, 1600] } as const;
const EXT = [".webp", ".png", ".jpg", ".jpeg", ".avif"];

async function main() {
  await mkdir(NEW_DIR, { recursive: true });

  // 1. replacements dropped into public/images/new/
  const incoming = new Map<string, string>(); // slot base name -> file path
  for (const f of await readdir(NEW_DIR)) {
    const ext = path.extname(f).toLowerCase();
    if (EXT.includes(ext)) incoming.set(path.basename(f, ext).toLowerCase(), path.join(NEW_DIR, f));
  }
  let replaced = 0;
  for (const slot of slotList) {
    const src = incoming.get(path.basename(slot.file, ".webp").toLowerCase());
    if (!src) continue;
    const [w, h] = SIZE_PX[slot.size];
    const out = path.join(DIR, slot.file);
    const tmp = `${out}.tmp`;
    await sharp(src)
      .rotate()
      .resize({ width: w, height: h, fit: "cover", position: "centre", withoutEnlargement: true })
      .webp({ quality: 80 })
      .toFile(tmp);
    await rm(out, { force: true });
    await import("node:fs/promises").then((fs) => fs.rename(tmp, out));
    await rm(src);
    incoming.delete(path.basename(slot.file, ".webp").toLowerCase());
    replaced++;
    console.log(`replaced ${slot.file} from new/`);
  }
  if (incoming.size) {
    console.warn(`new/ files that match no slot (left alone): ${[...incoming.values()].join(", ")}`);
  }

  // 2. blur placeholders
  const blurs: Record<string, string> = {};
  const missing: string[] = [];
  for (const slot of slotList) {
    const file = path.join(DIR, slot.file);
    if (!existsSync(file)) {
      missing.push(slot.key);
      continue;
    }
    const buf = await sharp(file).resize(16, 11, { fit: "cover" }).webp({ quality: 40 }).toBuffer();
    blurs[slot.key] = `data:image/webp;base64,${buf.toString("base64")}`;
  }
  const body = `// GENERATED by scripts/images-sync.ts (npm run images:sync). Do not edit.
// Tiny blur placeholders (16px WebP) keyed by slot key, shown while an image loads.
export const imageBlurs: Record<string, string> = ${JSON.stringify(blurs, null, 2)};
`;
  await writeFile(path.join("data", "image-blurs.ts"), body);
  console.log(
    `images:sync: ${Object.keys(blurs).length}/${slotList.length} slot images, ${replaced} replaced from new/, ` +
      `${missing.length} missing${missing.length ? ": " + missing.join(", ") : ""}`,
  );
}

await main();
